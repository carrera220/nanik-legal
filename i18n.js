  function t(code, key) {
    var pack = T[code] || T.en;
    return pack[key] || T.en[key] || key;
  }

  function normalize(code) {
    if (!code) return null;
    code = String(code).toLowerCase().replace('_', '-');
    if (code === 'nb' || code === 'nn') code = 'no';
    var short = code.split('-')[0];
    if (LOCALES.some(function (l) { return l.code === short; })) return short;
    return null;
  }

  function detect() {
    try {
      var saved = normalize(localStorage.getItem(STORAGE_KEY));
      if (saved) return saved;
    } catch (e) {}
    var nav = navigator.languages || [navigator.language];
    for (var i = 0; i < nav.length; i++) {
      var hit = normalize(nav[i]);
      if (hit) return hit;
    }
    return 'en';
  }

  function apply(code) {
    code = normalize(code) || 'en';
    try { localStorage.setItem(STORAGE_KEY, code); } catch (e) {}
    document.documentElement.lang = code;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = t(code, key);
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = val;
      else el.textContent = val;
    });

    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(code, el.getAttribute('data-i18n-title')));
    });

    var titleKey = document.body && document.body.getAttribute('data-i18n-page-title');
    if (titleKey) document.title = t(code, titleKey);

    var flagBtn = document.getElementById('site-lang-current');
    if (flagBtn) {
      var loc = localeByCode(code);
      flagBtn.textContent = (loc.flag ? loc.flag + ' ' : '') + String(loc.code || code).toUpperCase();
    }
  }

  function buildSwitcher() {
    var slot = document.getElementById('site-lang-slot') || document.querySelector('header.site .nav-shell') || document.querySelector('header.site nav');
    if (!slot || document.getElementById('site-lang-wrap')) return;

    var wrap = document.createElement('div');
    wrap.id = 'site-lang-wrap';
    wrap.className = 'site-lang-wrap';

    var button = document.createElement('button');
    button.type = 'button';
    button.id = 'site-lang-current';
    button.className = 'site-lang-current';
    button.setAttribute('aria-haspopup', 'listbox');
    button.setAttribute('aria-expanded', 'false');
    button.setAttribute('data-i18n-title', 'nav.langLabel');
    button.title = t(detect(), 'nav.langLabel');

    function labelFor(code) {
      var loc = localeByCode(code);
      return (loc.flag ? loc.flag + ' ' : '') + String(loc.code || code).toUpperCase();
    }
    button.textContent = labelFor(detect());

    var list = document.createElement('ul');
    list.className = 'site-lang-list';
    list.setAttribute('role', 'listbox');
    list.hidden = true;

    function closeList() {
      list.hidden = true;
      button.setAttribute('aria-expanded', 'false');
    }
    function openList() {
      list.hidden = false;
      button.setAttribute('aria-expanded', 'true');
    }

    ['primary', 'european'].forEach(function (group) {
      var heading = document.createElement('li');
      heading.className = 'site-lang-group-label';
      heading.setAttribute('data-i18n-label', group === 'primary' ? 'nav.groupPrimary' : 'nav.groupEuropean');
      heading.textContent = t('en', group === 'primary' ? 'nav.groupPrimary' : 'nav.groupEuropean');
      list.appendChild(heading);
      LOCALES.filter(function (l) { return l.group === group; }).forEach(function (loc) {
        var item = document.createElement('li');
        item.setAttribute('role', 'option');
        item.setAttribute('data-code', loc.code);
        item.textContent = loc.flag + ' ' + loc.native;
        item.addEventListener('click', function () {
          apply(loc.code);
          button.textContent = labelFor(loc.code);
          closeList();
        });
        list.appendChild(item);
      });
    });

    button.addEventListener('click', function (e) {
      e.stopPropagation();
      if (list.hidden) openList(); else closeList();
    });
    document.addEventListener('click', function (e) {
      if (!wrap.contains(e.target)) closeList();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeList();
    });

    wrap.appendChild(button);
    wrap.appendChild(list);
    slot.appendChild(wrap);
  }

  function init() {
    buildSwitcher();
    apply(detect());
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
